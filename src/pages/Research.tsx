import { useState } from "react";
import { useNavigate, useLocation } from "react-router-dom";
import { motion } from "framer-motion";
import { ArrowLeft, FlaskConical, Copy, Check, Download, BookOpen, Columns2, FileText, Quote, ChevronDown } from "lucide-react";
import BottomNav from "@/components/BottomNav";
import { useLanguage } from "@/i18n/LanguageContext";
import { toast } from "sonner";

const Research = () => {
  const navigate = useNavigate();
  const location = useLocation();
  const { t, dir } = useLanguage();
  const analysis = location.state?.analysis ?? null;
  const imageUrl = location.state?.imageUrl ?? null;

  const [activeTab, setActiveTab] = useState<"editor" | "compare" | "cite">("editor");
  const [leidenText, setLeidenText] = useState(analysis?.diplomatic?.content ?? "[---] L(ucius) SERGIVS [---]\nFIL(ius) MARC(i)\nDEC(urio) COL(oniae)\nTHAMVG(adensis)");
  const [normalizedText, setNormalizedText] = useState(analysis?.normalized?.content ?? "Lucius Sergius, filius Marci, decurio coloniae Thamugadiensis");
  const [copied, setCopied] = useState(false);
  const [citationStyle, setCitationStyle] = useState<"apa" | "bibtex" | "chicago">("apa");
  const [showCitationDropdown, setShowCitationDropdown] = useState(false);

  const fragmentId = analysis?.fragmentId ?? "TIMGAD-FRAG-042";
  const site = analysis?.site ?? "Timgad";
  const region = analysis?.region ?? "Batna, Algeria";

  const generateCitation = () => {
    const year = new Date().getFullYear();
    switch (citationStyle) {
      case "apa": return `Epigraphi Dz. (${year}). Inscription analysis: ${fragmentId}. AI-assisted epigraphic reading from ${site}, ${region}. Epigraphi Dz Platform. Retrieved ${new Date().toLocaleDateString("en-US", { month: "long", day: "numeric", year: "numeric" })}.`;
      case "bibtex": return `@misc{epigraphi_${fragmentId.toLowerCase().replace(/[^a-z0-9]/g, "_")},\n  title = {Inscription Analysis: ${fragmentId}},\n  author = {Epigraphi Dz},\n  year = {${year}},\n  howpublished = {Epigraphi Dz Platform},\n  note = {AI-assisted reading from ${site}, ${region}}\n}`;
      case "chicago": return `Epigraphi Dz. "${fragmentId}: Inscription Analysis." AI-assisted epigraphic reading. ${site}, ${region}. Epigraphi Dz, ${year}.`;
    }
  };

  const copyToClipboard = (text: string) => {
    navigator.clipboard.writeText(text);
    setCopied(true);
    toast.success(t("research", "copiedToClipboard"));
    setTimeout(() => setCopied(false), 2000);
  };

  const exportMarkdown = () => {
    const md = `# Inscription Analysis: ${fragmentId}\n## Site: ${site}, ${region}\n\n### Diplomatic Reading (Leiden Conventions)\n\`\`\`\n${leidenText}\n\`\`\`\n\n### Normalized Reading\n${normalizedText}\n\n### Expanded Reading\n${analysis?.expanded?.content ?? "N/A"}\n\n### Translation\n**Arabic:** ${analysis?.translation?.ar ?? "N/A"}\n**French:** ${analysis?.translation?.fr ?? "N/A"}\n**English:** ${analysis?.translation?.en ?? "N/A"}\n\n### AI Commentary\n${analysis?.aiCommentary ?? "N/A"}\n\n### References\n${(analysis?.references ?? []).map((r: string) => `- ${r}`).join("\n")}\n\n---\n*Generated by Epigraphi Dz — AI-Powered Heritage Digitization*\n*Citation: ${generateCitation()}*\n`;
    const blob = new Blob([md], { type: "text/markdown" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a"); a.href = url; a.download = `${fragmentId}-analysis.md`; a.click();
    URL.revokeObjectURL(url);
    toast.success(t("research", "reportExported"));
  };

  const tabs = [
    { id: "editor" as const, icon: FileText, label: t("research", "leidenEditor") },
    { id: "compare" as const, icon: Columns2, label: t("research", "compare") },
    { id: "cite" as const, icon: Quote, label: t("research", "cite") },
  ];

  const leidenLegend = [
    ["[abc]", t("research", "missingLettersRestored")],
    ["(abc)", t("research", "abbreviationExpanded")],
    ["[---]", t("research", "unspecifiedLostText")],
    ["⌜abc⌝", t("research", "correctionByScribe")],
    ["{{abc}}", t("research", "deliberatelyDeletedText")],
    ["vac.", t("research", "intentionalBlank")],
  ];

  return (
    <div className="flex min-h-screen flex-col bg-background pb-24">
      <div className="flex items-center justify-between px-4 pt-12 pb-4 border-b border-border/50 bg-card/30 backdrop-blur-md">
        <button onClick={() => navigate(-1)} className="text-foreground p-2 rounded-lg hover:bg-secondary transition-colors"><ArrowLeft className="w-5 h-5" /></button>
        <div className="flex items-center gap-2"><FlaskConical className="w-5 h-5 text-gold" /><h1 className="font-display text-sm font-bold tracking-wider uppercase gold-text">{t("research", "researchMode")}</h1></div>
        <button onClick={exportMarkdown} className="text-gold p-2 rounded-lg hover:bg-secondary transition-colors"><Download className="w-5 h-5" /></button>
      </div>

      <div className="px-4 py-3 bg-secondary/30 border-b border-border/30 flex items-center justify-between">
        <div className="flex items-center gap-2">
          <span className="text-[10px] font-display font-bold text-gold tracking-widest">{fragmentId}</span>
          <span className="text-[10px] text-muted-foreground">•</span>
          <span className="text-[10px] text-muted-foreground">{site}</span>
        </div>
        {analysis?.scriptType && <span className="text-[10px] bg-gold/10 text-gold px-2 py-0.5 rounded-full font-bold">{analysis.scriptType}</span>}
      </div>

      <div className="px-4 py-3 flex gap-2 border-b border-border/30">
        {tabs.map((tab) => (
          <button key={tab.id} onClick={() => setActiveTab(tab.id)} className={`flex items-center gap-2 px-4 py-2 rounded-lg text-xs font-bold transition-all ${activeTab === tab.id ? "gold-gradient text-primary-foreground shadow-lg shadow-gold/20" : "bg-secondary/50 text-muted-foreground hover:text-foreground"}`}>
            <tab.icon className="w-4 h-4" />{tab.label}
          </button>
        ))}
      </div>

      <div className="px-4 py-6 space-y-6 flex-1">
        {activeTab === "editor" && (
          <motion.div initial={{ opacity: 0 }} animate={{ opacity: 1 }} className="space-y-6">
            <div>
              <div className="flex items-center justify-between mb-2">
                <h3 className="font-display text-xs font-bold tracking-wider uppercase text-foreground">{t("research", "diplomaticText")}</h3>
                <button onClick={() => copyToClipboard(leidenText)} className="p-1.5 rounded-md hover:bg-secondary transition-colors">
                  {copied ? <Check className="w-4 h-4 text-success" /> : <Copy className="w-4 h-4 text-muted-foreground" />}
                </button>
              </div>
              <textarea value={leidenText} onChange={(e) => setLeidenText(e.target.value)} className="w-full h-40 bg-secondary/40 border border-border/50 rounded-xl p-4 font-mono text-sm text-foreground resize-none focus:outline-none focus:ring-1 focus:ring-gold/30 placeholder:text-muted-foreground" dir="ltr" placeholder={t("research", "enterLeidenText")} />
              <div className="mt-2 flex flex-wrap gap-2">
                {["[---]", "()", "⌜⌝", "{{  }}", "---", "vac.", "sic"].map((symbol) => (
                  <button key={symbol} onClick={() => setLeidenText(prev => prev + " " + symbol)} className="text-[10px] font-mono bg-secondary/60 text-muted-foreground px-2.5 py-1.5 rounded-md hover:bg-secondary hover:text-foreground transition-colors border border-border/30">{symbol}</button>
                ))}
              </div>
            </div>
            <div>
              <h3 className="font-display text-xs font-bold tracking-wider uppercase text-foreground mb-2">{t("research", "normalizedReading")}</h3>
              <textarea value={normalizedText} onChange={(e) => setNormalizedText(e.target.value)} className="w-full h-24 bg-secondary/40 border border-border/50 rounded-xl p-4 text-sm text-foreground resize-none focus:outline-none focus:ring-1 focus:ring-gold/30" dir="ltr" />
            </div>
            <div className="glass-card-gold p-4">
              <h4 className="font-display text-[10px] font-bold tracking-wider uppercase text-gold mb-3">{t("research", "leidenLegend")}</h4>
              <div className="grid grid-cols-2 gap-2 text-[11px]">
                {leidenLegend.map(([symbol, desc], i) => (
                  <div key={i} className="flex items-start gap-2"><code className="text-gold font-mono shrink-0">{symbol}</code><span className="text-muted-foreground">{desc}</span></div>
                ))}
              </div>
            </div>
          </motion.div>
        )}

        {activeTab === "compare" && (
          <motion.div initial={{ opacity: 0 }} animate={{ opacity: 1 }} className="space-y-4">
            <h3 className="font-display text-xs font-bold tracking-wider uppercase text-foreground">{t("research", "sideBySide")}</h3>
            <div className="grid grid-cols-2 gap-3">
              <div className="glass-card-gold p-3 rounded-xl">
                <p className="text-[10px] font-display font-bold text-gold tracking-widest mb-2">{t("research", "image")}</p>
                <div className="rounded-lg overflow-hidden bg-secondary h-40"><img src={imageUrl ?? "/images/inscription.jpg"} alt="Inscription" className="w-full h-full object-cover" /></div>
              </div>
              <div className="glass-card-gold p-3 rounded-xl">
                <p className="text-[10px] font-display font-bold text-gold tracking-widest mb-2">DIPLOMATIC</p>
                <div className="bg-secondary/40 rounded-lg p-3 h-40 overflow-y-auto"><p className="font-mono text-xs text-foreground leading-relaxed whitespace-pre-wrap">{leidenText}</p></div>
              </div>
            </div>
            <div className="grid grid-cols-2 gap-3">
              <div className="glass-card-gold p-3 rounded-xl">
                <p className="text-[10px] font-display font-bold text-gold tracking-widest mb-2">NORMALIZED</p>
                <div className="bg-secondary/40 rounded-lg p-3"><p className="text-xs text-foreground leading-relaxed">{normalizedText}</p></div>
              </div>
              <div className="glass-card-gold p-3 rounded-xl">
                <p className="text-[10px] font-display font-bold text-gold tracking-widest mb-2">EXPANDED</p>
                <div className="bg-secondary/40 rounded-lg p-3"><p className="text-xs text-foreground leading-relaxed">{analysis?.expanded?.content ?? "Lucius Sergius, filius Marci, decurio coloniae Thamugadiensis."}</p></div>
              </div>
            </div>
            <div className="glass-card-gold p-4 rounded-xl">
              <p className="text-[10px] font-display font-bold text-gold tracking-widest mb-3">{t("research", "translations")}</p>
              <div className="space-y-3">
                {[
                  { lang: "العربية", text: analysis?.translation?.ar ?? "لوسيوس سيرجيوس، ابن ماركوس، عضو مجلس مستعمرة تيمقاد.", rtl: true },
                  { lang: "Français", text: analysis?.translation?.fr ?? "Lucius Sergius, fils de Marcus, décurion de la colonie de Thamugadi.", rtl: false },
                  { lang: "English", text: analysis?.translation?.en ?? "Lucius Sergius, son of Marcus, decurion of the colony of Thamugadi.", rtl: false },
                ].map((tr, i) => (
                  <div key={i} className="bg-secondary/30 rounded-lg p-3">
                    <p className="text-[10px] font-bold text-muted-foreground mb-1">{tr.lang}</p>
                    <p className="text-xs text-foreground leading-relaxed" dir={tr.rtl ? "rtl" : "ltr"}>{tr.text}</p>
                  </div>
                ))}
              </div>
            </div>
          </motion.div>
        )}

        {activeTab === "cite" && (
          <motion.div initial={{ opacity: 0 }} animate={{ opacity: 1 }} className="space-y-6">
            <div>
              <h3 className="font-display text-xs font-bold tracking-wider uppercase text-foreground mb-4">{t("research", "generateCitation")}</h3>
              <div className="relative mb-4">
                <button onClick={() => setShowCitationDropdown(!showCitationDropdown)} className="w-full flex items-center justify-between bg-secondary/40 border border-border/50 rounded-xl px-4 py-3 text-sm text-foreground">
                  <span>{citationStyle === "apa" ? "APA 7th Edition" : citationStyle === "bibtex" ? "BibTeX" : "Chicago"}</span>
                  <ChevronDown className={`w-4 h-4 transition-transform ${showCitationDropdown ? "rotate-180" : ""}`} />
                </button>
                {showCitationDropdown && (
                  <div className="absolute top-full left-0 right-0 mt-1 bg-card border border-border rounded-xl overflow-hidden z-20 shadow-lg">
                    {(["apa", "bibtex", "chicago"] as const).map((style) => (
                      <button key={style} onClick={() => { setCitationStyle(style); setShowCitationDropdown(false); }} className={`w-full px-4 py-3 text-sm text-left hover:bg-secondary transition-colors ${citationStyle === style ? "text-gold font-bold" : "text-foreground"}`}>
                        {style === "apa" ? "APA 7th Edition" : style === "bibtex" ? "BibTeX" : "Chicago Manual of Style"}
                      </button>
                    ))}
                  </div>
                )}
              </div>
              <div className="glass-card-gold p-4 rounded-xl group relative">
                <p className={`text-sm text-foreground leading-relaxed ${citationStyle === "bibtex" ? "font-mono text-xs" : ""}`}>{generateCitation()}</p>
                <button onClick={() => copyToClipboard(generateCitation())} className="absolute top-3 right-3 p-1.5 rounded-md bg-background/50 opacity-0 group-hover:opacity-100 transition-opacity">
                  {copied ? <Check className="w-4 h-4 text-success" /> : <Copy className="w-4 h-4 text-muted-foreground" />}
                </button>
              </div>
            </div>
            <div>
              <div className="flex items-center gap-2 mb-3"><BookOpen className="w-4 h-4 text-gold" /><h3 className="font-display text-xs font-bold tracking-wider uppercase text-foreground">{t("research", "sourceReferences")}</h3></div>
              <div className="space-y-2">
                {(analysis?.references ?? ["CIL VIII 2394", "ILAlg II/3 7683", "EDH HD031234"]).map((ref: string, i: number) => (
                  <div key={i} className="flex items-start gap-2 bg-secondary/30 rounded-lg p-3">
                    <span className="text-[9px] font-bold text-gold bg-gold/10 px-2 py-0.5 rounded-full mt-0.5 shrink-0">[{i + 1}]</span>
                    <p className="text-[12px] text-muted-foreground leading-relaxed font-mono">{ref}</p>
                  </div>
                ))}
              </div>
            </div>
            <button onClick={exportMarkdown} className="flex items-center justify-center h-14 w-full gold-gradient text-primary-foreground font-bold rounded-xl shadow-lg shadow-gold/20 font-display tracking-wider">
              <Download className="w-5 h-5 mr-3" />{t("research", "exportFullReport")}
            </button>
          </motion.div>
        )}
      </div>

      <BottomNav active="analyze" />
    </div>
  );
};

export default Research;
